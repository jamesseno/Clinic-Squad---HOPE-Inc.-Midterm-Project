SELECT to_regclass('public.password_reset_token');CREATE TABLE public.password_reset_token (
    password_reset_token_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES public.app_user (id) ON DELETE CASCADE,
    token_hash text NOT NULL,
    expires_at timestamptz NOT NULL,
    used boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX password_reset_token_user_id_idx
    ON public.password_reset_token (user_id);

CREATE UNIQUE INDEX password_reset_token_token_hash_uidx
    ON public.password_reset_token (token_hash);

ALTER TABLE public.password_reset_token ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.password_reset_token FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.password_reset_token TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.password_reset_token_password_reset_token_id_seq
    TO service_role;

CREATE OR REPLACE FUNCTION app_private.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END
$$;

REVOKE ALL ON FUNCTION app_private.set_updated_at() FROM PUBLIC, anon, authenticated;

CREATE TRIGGER password_reset_token_set_updated_at
    BEFORE UPDATE ON public.password_reset_token
    FOR EACH ROW EXECUTE FUNCTION app_private.set_updated_at();
