CREATE SCHEMA IF NOT EXISTS app_private;
REVOKE ALL ON SCHEMA app_private FROM PUBLIC;
GRANT USAGE ON SCHEMA app_private TO authenticated;

CREATE TABLE public.app_role (
    role_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code text NOT NULL UNIQUE
        CHECK (role_code IN ('superadmin', 'admin', 'user')),
    role_name text NOT NULL,
    description text,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.module (
    module_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_code text NOT NULL UNIQUE,
    module_name text NOT NULL UNIQUE,
    description text,
    display_order integer NOT NULL DEFAULT 0,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT module_code_not_blank CHECK (btrim(module_code) <> ''),
    CONSTRAINT module_name_not_blank CHECK (btrim(module_name) <> '')
);

CREATE TABLE public.rights_catalog (
    right_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id integer NOT NULL REFERENCES public.module (module_id) ON DELETE RESTRICT,
    right_code text NOT NULL,
    right_name text NOT NULL,
    description text,
    display_order integer NOT NULL DEFAULT 0,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT rights_catalog_module_code_unique UNIQUE (module_id, right_code),
    CONSTRAINT rights_catalog_code_not_blank CHECK (btrim(right_code) <> ''),
    CONSTRAINT rights_catalog_name_not_blank CHECK (btrim(right_name) <> '')
);

CREATE TABLE public.app_user (
    id uuid PRIMARY KEY REFERENCES auth.users (id) ON DELETE CASCADE,
    email text NOT NULL,
    first_name text NOT NULL,
    last_name text NOT NULL,
    role_id integer NOT NULL REFERENCES public.app_role (role_id) ON DELETE RESTRICT,
    account_status text NOT NULL DEFAULT 'pending'
        CHECK (account_status IN ('pending', 'active')),
    is_blocked boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT app_user_email_not_blank CHECK (btrim(email) <> ''),
    CONSTRAINT app_user_first_name_not_blank CHECK (btrim(first_name) <> ''),
    CONSTRAINT app_user_last_name_not_blank CHECK (btrim(last_name) <> '')
);

CREATE UNIQUE INDEX app_user_email_lower_unique ON public.app_user (lower(email));
CREATE INDEX app_user_role_id_idx ON public.app_user (role_id);

CREATE TABLE public.user_permission (
    user_permission_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES public.app_user (id) ON DELETE CASCADE,
    right_id integer NOT NULL REFERENCES public.rights_catalog (right_id) ON DELETE RESTRICT,
    is_deleted boolean NOT NULL DEFAULT false,
    deleted_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT user_permission_user_right_unique UNIQUE (user_id, right_id),
    CONSTRAINT user_permission_soft_delete_consistent
        CHECK (is_deleted = (deleted_at IS NOT NULL))
);

CREATE INDEX user_permission_right_id_idx ON public.user_permission (right_id);

CREATE OR REPLACE FUNCTION app_private.current_role_code()
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT r.role_code
    FROM public.app_user AS app_user
    JOIN public.app_role AS r USING (role_id)
    WHERE app_user.id = auth.uid()
      AND app_user.account_status = 'active'
      AND NOT app_user.is_blocked
$$;

CREATE OR REPLACE FUNCTION app_private.can_manage_user(target_user_id uuid)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT CASE app_private.current_role_code()
        WHEN 'superadmin' THEN EXISTS (
            SELECT 1
            FROM public.app_user
            WHERE id = target_user_id
        )
        WHEN 'admin' THEN EXISTS (
            SELECT 1
            FROM public.app_user AS target_user
            JOIN public.app_role AS target_role USING (role_id)
            WHERE target_user.id = target_user_id
              AND target_role.role_code = 'user'
        )
        ELSE false
    END
$$;

CREATE OR REPLACE FUNCTION app_private.guard_app_user_update()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    IF app_private.current_role_code() = 'admin'
       AND (
           NEW.role_id IS DISTINCT FROM OLD.role_id
           OR NEW.account_status IS DISTINCT FROM OLD.account_status
       ) THEN
        RAISE EXCEPTION 'Admins cannot change a user role or approval status';
    END IF;

    NEW.updated_at := now();
    RETURN NEW;
END
$$;

REVOKE ALL ON FUNCTION app_private.current_role_code() FROM PUBLIC;
REVOKE ALL ON FUNCTION app_private.can_manage_user(uuid) FROM PUBLIC;
REVOKE ALL ON FUNCTION app_private.guard_app_user_update() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION app_private.current_role_code() TO authenticated;
GRANT EXECUTE ON FUNCTION app_private.can_manage_user(uuid) TO authenticated;

ALTER TABLE public.app_role ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.module ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.rights_catalog ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.app_user ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_permission ENABLE ROW LEVEL SECURITY;

CREATE TRIGGER app_user_guard_update
    BEFORE UPDATE ON public.app_user
    FOR EACH ROW EXECUTE FUNCTION app_private.guard_app_user_update();

GRANT SELECT ON public.app_role, public.module, public.rights_catalog TO authenticated;
GRANT SELECT, INSERT, UPDATE ON public.app_user TO authenticated;
GRANT SELECT, INSERT, UPDATE ON public.user_permission TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.user_permission_user_permission_id_seq TO authenticated;

CREATE POLICY "Authenticated users can read roles"
    ON public.app_role FOR SELECT TO authenticated
    USING (true);

CREATE POLICY "Authenticated users can read modules"
    ON public.module FOR SELECT TO authenticated
    USING (true);

CREATE POLICY "Authenticated users can read rights catalogue"
    ON public.rights_catalog FOR SELECT TO authenticated
    USING (true);

CREATE POLICY "Users can read their own profile and managers can read managed users"
    ON public.app_user FOR SELECT TO authenticated
    USING (id = auth.uid() OR app_private.can_manage_user(id));

CREATE POLICY "Users can create only their pending standard-user profile"
    ON public.app_user FOR INSERT TO authenticated
    WITH CHECK (
        id = auth.uid()
        AND account_status = 'pending'
        AND NOT is_blocked
        AND role_id = (
            SELECT role_id
            FROM public.app_role
            WHERE role_code = 'user'
        )
    );

CREATE POLICY "Managers can update users within their role scope"
    ON public.app_user FOR UPDATE TO authenticated
    USING (app_private.can_manage_user(id))
    WITH CHECK (
        app_private.current_role_code() = 'superadmin'
        OR (
            app_private.current_role_code() = 'admin'
            AND role_id = (
                SELECT role_id
                FROM public.app_role
                WHERE role_code = 'user'
            )
        )
    );

CREATE POLICY "Users can read active permissions and managers can read managed users' permissions"
    ON public.user_permission FOR SELECT TO authenticated
    USING (
        (user_id = auth.uid() AND NOT is_deleted)
        OR app_private.can_manage_user(user_id)
    );

CREATE POLICY "Managers can grant permissions to managed users"
    ON public.user_permission FOR INSERT TO authenticated
    WITH CHECK (
        NOT is_deleted
        AND app_private.can_manage_user(user_id)
    );

CREATE POLICY "Managers can update permissions for managed users"
    ON public.user_permission FOR UPDATE TO authenticated
    USING (app_private.can_manage_user(user_id))
    WITH CHECK (app_private.can_manage_user(user_id));
