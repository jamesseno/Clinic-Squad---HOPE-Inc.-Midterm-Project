CREATE TABLE public.role_permission (
    role_permission_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id integer NOT NULL REFERENCES public.app_role (role_id) ON DELETE CASCADE,
    right_id integer NOT NULL REFERENCES public.rights_catalog (right_id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT role_permission_role_right_unique UNIQUE (role_id, right_id)
);

CREATE INDEX role_permission_right_id_idx
    ON public.role_permission (right_id);

ALTER TABLE public.role_permission ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.role_permission TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.role_permission TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.role_permission_role_permission_id_seq
    TO service_role;

CREATE POLICY "Authenticated users can read role permissions"
    ON public.role_permission FOR SELECT TO authenticated
    USING (true);
